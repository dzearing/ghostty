//! Generates the `release_notes_data` module: every `release-notes/client/
//! <version>.json` and `release-notes/agent/<version>.json` in the repo,
//! embedded in the binary (T624).
//!
//! macOS ships these as loose files under
//! `Contents/Resources/ghostty/release-notes/` (`GhosttyResources.zig`) and
//! reads the directory at runtime. A Windows exe has no Resources directory
//! and the portable ZIP is a flat folder, so the Windows equivalent of "in
//! the app bundle" is "in the exe" — the same call `GhosttyAssets.zig` made
//! for the skill and hook assets.
//!
//! The list is GENERATED rather than hand-written for one reason: the release
//! process adds a `<version>.json` on the way to every tag, and a hand-kept
//! `@embedFile` list is a thing to forget on exactly the day it matters. This
//! enumerates the directories at configure time, so a note file that exists is
//! a note file that ships, and one that is deleted stops shipping.
const GhosttyReleaseNotes = @This();

const std = @import("std");

/// The generated `release_notes_data.zig`.
output: std.Build.LazyPath,

/// The two scopes, mirroring the repo layout and Mac's two bundled
/// directories: `client/` is app/UI/viewer/banner news, `agent/` is
/// session-persistence news.
const scopes = [_][]const u8{ "client", "agent" };

pub fn init(b: *std.Build) !GhosttyReleaseNotes {
    const wf = b.addWriteFiles();

    var src: std.ArrayList(u8) = .empty;
    const gpa = b.allocator;
    try src.appendSlice(gpa,
        \\//! This file is auto-generated by src/build/GhosttyReleaseNotes.zig.
        \\//! Do not edit. See release-notes/README.md.
        \\
        \\/// One bundled notes file: the version it is keyed by (the bare
        \\/// semver of its filename) and its raw JSON text.
        \\pub const Entry = struct { version: []const u8, json: []const u8 };
        \\
        \\
    );

    for (scopes) |scope| {
        var names: std.ArrayList([]const u8) = .empty;
        defer names.deinit(gpa);

        const rel = b.fmt("release-notes/{s}", .{scope});
        if (b.build_root.handle.openDir(rel, .{ .iterate = true })) |dir_const| {
            var dir = dir_const;
            defer dir.close();
            var it = dir.iterate();
            while (try it.next()) |entry| {
                if (entry.kind != .file) continue;
                if (!std.mem.endsWith(u8, entry.name, ".json")) continue;
                try names.append(gpa, b.dupe(entry.name));
            }
        } else |_| {
            // No directory is not a build failure: a source tree without
            // notes yields an empty list and a "no release notes" window.
        }

        // Directory iteration order is filesystem order, which differs
        // between machines and would make the generated file — and therefore
        // the build cache hash — nondeterministic.
        std.mem.sort([]const u8, names.items, {}, lessThanAscii);

        try src.writer(gpa).print("pub const {s} = [_]Entry{{\n", .{scope});
        for (names.items) |name| {
            const version = name[0 .. name.len - ".json".len];
            const embed_path = b.fmt("{s}/{s}", .{ scope, name });
            _ = wf.addCopyFile(
                b.path(b.fmt("release-notes/{s}/{s}", .{ scope, name })),
                embed_path,
            );
            try src.writer(gpa).print(
                "    .{{ .version = \"{s}\", .json = @embedFile(\"{s}\") }},\n",
                .{ version, embed_path },
            );
        }
        try src.appendSlice(gpa, "};\n\n");
    }

    return .{ .output = wf.add("release_notes_data.zig", src.items) };
}

fn lessThanAscii(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// Add the "release_notes_data" import.
pub fn addImport(self: *const GhosttyReleaseNotes, step: *std.Build.Step.Compile) void {
    self.output.addStepDependencies(&step.step);
    step.root_module.addAnonymousImport("release_notes_data", .{
        .root_source_file = self.output,
    });
}
